#!/usr/bin/env python3
"""Generate OpenMSDIA's COM declarations from a harvested type library.

Input:  phase0/snapshots/<dll>/typelib.json (typelib_dump.c output). Only
        interface *facts* from the type library are used: names, GUIDs,
        vtable slots, parameter types and enum values.
Output (into --out):
  dia2_gen.h        enums, records, CLSIDs/IIDs and C++ interface classes
                    (pure virtual, STDMETHODCALLTYPE, no destructor), so their
                    vtables are COM vtables.
  dia2_stubs_gen.h  Stub_<I><Base>: default implementations of every method
                    of <I> and its bases that return OPENMSDIA_STUB_RESULT(slot)
                    (E_NOTIMPL unless the includer overrides it).
  dia2_meta_gen.h   tables for tools: interfaces with IID and slot count, and
                    every property getter with its slot and value kind.

Standard OLE interfaces (IUnknown, IStream, ISequentialStream, IEnumUnknown)
come from the system headers and are not generated.
"""
import argparse, json, os, sys

SYSTEM_IFACES = {"IUnknown", "IStream", "ISequentialStream", "IEnumUnknown"}
RECORD_MAP = {"GUID": "GUID", "_ULARGE_INTEGER": "ULARGE_INTEGER",
              "_LARGE_INTEGER": "LARGE_INTEGER", "tagSTATSTG": "STATSTG",
              "_FILETIME": "FILETIME"}
VT_MAP = {"HRESULT": "HRESULT", "ULONG": "ULONG", "long": "LONG",
          "ULONGLONG": "ULONGLONG", "LONGLONG": "LONGLONG", "LPWSTR": "LPWSTR",
          "BSTR": "BSTR", "BYTE": "BYTE", "USHORT": "USHORT", "short": "SHORT",
          "VARIANT": "VARIANT", "void": "void", "int": "int", "UINT": "UINT",
          "IUnknown*": "IUnknown *", "char": "CHAR", "float": "float",
          "double": "double"}


def ctype(t, types):
    if "ptr" in t:
        return ctype(t["ptr"], types) + " *"
    if "vt" in t:
        return VT_MAP[t["vt"]]
    if "ref" in t:
        r = t["ref"]
        if r in RECORD_MAP:
            return RECORD_MAP[r]
        k = types[r]["kind"] if r in types else None
        if k == "enum":
            return "enum " + r
        return r
    if "carray" in t:
        raise ValueError("carray only in records")
    raise ValueError(t)


def method_name(f):
    n = f["name"]
    if f["kind"] == "propget":
        return "get_" + n
    if f["kind"] == "propput":
        return "put_" + n
    if n.startswith("__MIDL_"):
        # A type library artefact: the slot exists, its name does not.
        return "__midl_slot%d" % f["slot"]
    return n


def guid_init(g):
    a, b, c, d, e = g.split("-")
    by = [d[0:2], d[2:4]] + [e[i:i + 2] for i in range(0, 12, 2)]
    return "{0x%s, 0x%s, 0x%s, {%s}}" % (a, b, c, ", ".join("0x" + x for x in by))


def guid_args(g):
    a, b, c, d, e = g.split("-")
    by = [d[0:2], d[2:4]] + [e[i:i + 2] for i in range(0, 12, 2)]
    return "0x%s, 0x%s, 0x%s, %s" % (a, b, c, ", ".join("0x" + x for x in by))


def params(f, types, named=True):
    out = []
    for i, p in enumerate(f["params"]):
        ct = ctype(p["type"], types)
        out.append("%s %s" % (ct, p["name"]) if named else ct)
    return ", ".join(out) if out else "void"


def value_kind(t):
    """Value kind of a getter's single out parameter, for tools."""
    if "ptr" not in t:
        return None
    inner = t["ptr"]
    if "vt" in inner:
        return {"long": "LONG", "ULONG": "ULONG", "ULONGLONG": "ULONGLONG",
                "BSTR": "BSTR", "VARIANT": "VARIANT", "IUnknown*": "UNKNOWN",
                "USHORT": "USHORT", "BYTE": "BYTE"}.get(inner["vt"])
    if "ref" in inner and inner["ref"] == "GUID":
        return "GUID"
    if "ptr" in inner and "ref" in inner["ptr"]:
        return "IFACE:" + inner["ptr"]["ref"]
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("typelib")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    tl = json.load(open(a.typelib))
    types = {t["name"]: t for t in tl["types"]}
    order = [t for t in tl["types"]]
    ifaces = [t for t in order if t["kind"] == "interface" and t["name"] not in SYSTEM_IFACES]
    banner = ("/* Generated by tools/gen_dia.py from the harvested type library\n"
              " * %s %s (syskind %s). Do not edit. */\n" % (tl["library"], tl["version"], tl["syskind"]))

    def base_of(t):
        return t["implements"][0]["name"] if t.get("implements") else "IUnknown"

    def chain(t):
        c = []
        while t is not None:
            c.append(t)
            b = base_of(t)
            t = types.get(b) if b not in SYSTEM_IFACES else None
        return list(reversed(c))

    def first_slot(t):
        b = base_of(t)
        if b == "IUnknown":
            return 3
        if b == "IEnumUnknown":
            return 7
        if b in SYSTEM_IFACES:
            raise ValueError(b)
        bt = types[b]
        return max(f["slot"] for f in bt["funcs"]) + 1

    # sanity: own slots contiguous and starting after the base
    for t in ifaces:
        slots = [f["slot"] for f in t["funcs"]]
        exp = list(range(first_slot(t), first_slot(t) + len(slots)))
        if slots != exp:
            sys.exit("%s: slots %s, expected %s" % (t["name"], slots, exp))

    # ---- dia2_gen.h
    L = [banner, "#ifndef OPENMSDIA_DIA2_GEN_H", "#define OPENMSDIA_DIA2_GEN_H", "",
         "#include <windows.h>", "#include <objbase.h>", "#include <oaidl.h>", "",
         "#ifndef __cplusplus", "#error dia2_gen.h declares C++ interface classes", "#endif", ""]
    L.append("/* Library %s %s */" % (tl["library"], tl["version"]))
    L.append("inline constexpr GUID LIBID_%s = %s;" % (tl["library"], guid_init(tl["guid"])))
    L.append("")
    for t in order:
        if t["kind"] == "enum":
            L.append("enum %s {" % t["name"])
            for m in t["members"]:
                L.append("    %s = %d," % (m["name"], m["value"]))
            L.append("};")
            L.append("")
    for t in order:
        if t["kind"] == "record" and t["name"] not in RECORD_MAP:
            L.append("struct %s {" % t["name"])
            for m in t["members"]:
                ty = m["type"]
                if "carray" in ty:
                    L.append("    %s %s[%s];" % (ctype(ty["carray"], types), m["name"],
                                                "][".join(str(x) for x in ty["dims"])))
                else:
                    L.append("    %s %s;" % (ctype(ty, types), m["name"]))
            L.append("};")
            L.append("static_assert(sizeof(struct %s) == %d, \"record size\");" % (t["name"], t["size"]))
            L.append("")
    for t in ifaces:
        L.append("struct %s;" % t["name"])
    L.append("")
    for t in order:
        if t["kind"] == "coclass":
            L.append("inline constexpr CLSID CLSID_%s = %s;" % (t["name"], guid_init(t["guid"])))
    L.append("")
    for t in ifaces:
        n = t["name"]
        L.append("inline constexpr IID IID_%s = %s;" % (n, guid_init(t["guid"])))
        L.append("struct %s : public %s {" % (n, base_of(t)))
        for f in t["funcs"]:
            L.append("    /* slot %d */ virtual %s STDMETHODCALLTYPE %s(%s) = 0;" % (
                f["slot"], ctype(f["ret"], types), method_name(f), params(f, types)))
        L.append("};")
        L.append("__CRT_UUID_DECL(%s, %s)" % (n, guid_args(t["guid"])))
        L.append("")
    L.append("#endif")
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, "dia2_gen.h"), "w").write("\n".join(L) + "\n")

    # ---- dia2_stubs_gen.h
    S = [banner, "#ifndef OPENMSDIA_DIA2_STUBS_GEN_H", "#define OPENMSDIA_DIA2_STUBS_GEN_H", "",
         '#include "dia2_gen.h"', "",
         "#ifndef OPENMSDIA_STUB_RESULT", "#define OPENMSDIA_STUB_RESULT(slot) E_NOTIMPL", "#endif", ""]
    for t in ifaces:
        n = t["name"]
        b = base_of(t)
        parent = "Base" if b in SYSTEM_IFACES else "Stub_%s<Base>" % b
        S.append("template <class Base = %s> struct Stub_%s : %s {" % (n, n, parent))
        for f in t["funcs"]:
            ret = ctype(f["ret"], types)
            body = "return OPENMSDIA_STUB_RESULT(%d);" % f["slot"] if ret == "HRESULT" else \
                   ("" if ret == "void" else "return (%s)0;" % ret)
            S.append("    %s STDMETHODCALLTYPE %s(%s) override { %s }" % (
                ret, method_name(f), params(f, types, named=False), body))
        S.append("};")
        S.append("")
    S.append("/* X(interface, first own slot, slot count including IUnknown) */")
    S.append("#define OPENMSDIA_FOR_EACH_INTERFACE(X) \\")
    for t in ifaces:
        S.append("    X(%s, %d, %d) \\" % (t["name"], first_slot(t), max(f["slot"] for f in t["funcs"]) + 1))
    S.append("")
    S.append("#endif")
    open(os.path.join(a.out, "dia2_stubs_gen.h"), "w").write("\n".join(S) + "\n")

    # ---- dia2_meta_gen.h (plain C tables)
    M = [banner, "#ifndef OPENMSDIA_DIA2_META_GEN_H", "#define OPENMSDIA_DIA2_META_GEN_H", "",
         "struct dia_iface_info { const char *name; const char *base; GUID iid; int first_slot; int nslots; };",
         "struct dia_getter_info { const char *iface; const char *name; int slot; const char *kind; };", "",
         "static const struct dia_iface_info dia_ifaces[] = {"]
    for t in ifaces:
        M.append('    {"%s", "%s", %s, %d, %d},' % (t["name"], base_of(t), guid_init(t["guid"]),
                                                    first_slot(t), max(f["slot"] for f in t["funcs"]) + 1))
    M.append("};")
    M.append("")
    M.append("/* propget methods with a single [out, retval] parameter */")
    M.append("static const struct dia_getter_info dia_getters[] = {")
    for t in ifaces:
        for f in t["funcs"]:
            if f["kind"] != "propget" or len(f["params"]) != 1:
                continue
            k = value_kind(f["params"][0]["type"])
            if k:
                M.append('    {"%s", "%s", %d, "%s"},' % (t["name"], f["name"], f["slot"], k))
    M.append("};")
    M.append("")
    M.append("#endif")
    open(os.path.join(a.out, "dia2_meta_gen.h"), "w").write("\n".join(M) + "\n")


if __name__ == "__main__":
    main()
